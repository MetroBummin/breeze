import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const read=p=>readFileSync(new URL('../../'+p,import.meta.url),'utf8');
const cohort=JSON.parse(read('tools/rss-evaluation/cohort.json'));
assert.equal(cohort.length,106);assert.equal(new Set(cohort.map(x=>x.url)).size,106);
assert.ok(cohort.every(x=>Object.keys(x).sort().join(',')==='id,source,split,title,url'));
const functionSource=read('supabase/functions/rss-eval-106/index.ts');
assert.ok(!functionSource.includes('reference_only'));
const db=new PGlite();
await db.exec('create role anon;create role authenticated;create role service_role bypassrls;');
await db.exec(read('tools/rss-evaluation/setup.sql'));
assert.equal((await db.query('select count(*)::int as n from breeze_rss_eval_106')).rows[0].n,106);
await db.exec('set role anon');
await assert.rejects(db.query('select * from breeze_rss_eval_106'),/permission denied/);
await assert.rejects(db.query("select claim_breeze_rss_eval_106('RSS-001')"),/permission denied/);
await db.exec('set role authenticated');
await assert.rejects(db.query('select * from breeze_rss_eval_106'),/permission denied/);
await db.exec('set role service_role');
const claim=async id=>(await db.query('select claim_breeze_rss_eval_106($1) as result',[id])).rows[0].result;
assert.equal((await claim('RSS-001')).claimed,true);
assert.equal((await claim('RSS-001')).claimed,false);
assert.equal((await claim('RSS-002')).claimed,true);
assert.equal((await claim('RSS-003')).claimed,false);
await db.exec("update breeze_rss_eval_106 set status='error' where id='RSS-001'");
assert.equal((await claim('RSS-001')).claimed,false,'error must never cause a paid retry');
assert.equal((await claim('RSS-003')).claimed,true);
await assert.rejects(claim('RSS-999'),/unknown article/);
await assert.rejects(db.exec("insert into breeze_rss_eval_106(id,url,source,title) values('RSS-107','https://example.com','extra','extra')"),/permission denied/);
await db.close();
console.log('106 unique public inputs; no notes in input; RLS, 2 slots, 106 cap and no-retry claims verified');
