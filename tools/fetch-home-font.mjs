/* Penpot Home section headings. Keep the font local, including in offline/native builds. */
import {writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const get=async(url,binary=false)=>{const res=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0 AppleWebKit/537.36 Chrome/128.0.0.0 Safari/537.36'}});if(!res.ok)throw new Error(`${res.status}: ${url}`);return binary?Buffer.from(await res.arrayBuffer()):res.text()};
const css=await get('https://fonts.googleapis.com/css2?family=Noto+Sans+KR:wght@700&text='+encodeURIComponent('가벼운 글긴 글CasualsBooks'));
const url=css.match(/url\((https:[^)]+)\)\s*format\('woff2'\)/)?.[1];
if(!url)throw new Error('Missing WOFF2 URL');
const font=await get(url,true);
writeFileSync(new URL('assets/fonts/noto-sans-kr-home-700.woff2',root),font);
writeFileSync(new URL('assets/fonts/OFL-NotoSansKR.txt',root),await get('https://raw.githubusercontent.com/google/fonts/main/ofl/notosanskr/OFL.txt'));
const hash=createHash('sha256').update(font).digest('hex').slice(0,8);
writeFileSync(new URL('styles/home-font.css',root),`/* Generated by tools/fetch-home-font.mjs. */\n@font-face{font-family:'Noto Sans KR';font-style:normal;font-weight:700;font-display:swap;src:url('../assets/fonts/noto-sans-kr-home-700.woff2?v=${hash}') format('woff2');}\n`);
console.log(`Home heading font: ${font.length} bytes`);
